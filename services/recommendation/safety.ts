/**
 * Безопасность «красной зоны»: детерминированное распознавание кризисных
 * высказываний (мысли о self-harm/суициде) ДО обращения к LLM.
 *
 * Чистая функция без I/O — работает офлайн и на сервере одинаково. По сигналу
 * клиент показывает экран экстренной помощи и НЕ сохраняет запись в историю.
 */

/** Сигнальная ошибка: «не сохранять, показать помощь». */
export class CrisisDetectedError extends Error {
  constructor() {
    super('crisis_detected');
    this.name = 'CrisisDetectedError';
  }
}

/** Полные фразы и сильные корневые токены (регистр не важен). */
const CRISIS_PHRASES: readonly string[] = [
  'хочу исчезнуть',
  'исчезнуть навсегда',
  'нет сил жить',
  'не хочу жить',
  'не хочется жить',
  'убить себя',
  'покончить с собой',
  'покончить с жизнью',
  'свести счёты с жизнью',
  'свести счеты с жизнью',
  'навредить себе',
  'наложить на себя руки',
  'перерезать вены',
  'хочу умереть',
  'хочу сдохнуть',
  'уйти из жизни',
  'не вижу смысла жить',
  'зачем жить',
  'лучше бы меня не было',
  'не хочу просыпаться',
  'суицид',
  'суицидальн',
  'селфхарм',
];

/** Есть ли в тексте кризисные высказывания (без учёта регистра). */
export const detectCrisis = (input: string): boolean => {
  if (!input) return false;
  const text = input.toLowerCase();
  return CRISIS_PHRASES.some((phrase) => text.includes(phrase));
};
