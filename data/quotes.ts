export function getQuoteForDay(): Quote {
  const today = new Date();
  const dayIndex = (today.getDate() + today.getMonth() * 31) % LOCAL_QUOTES.length;
  return LOCAL_QUOTES[dayIndex];
}

export function getRandomQuote(excludeText?: string): Quote {
  const filtered = excludeText ? LOCAL_QUOTES.filter(q => q.text !== excludeText) : LOCAL_QUOTES;
  const randomIndex = Math.floor(Math.random() * filtered.length);
  return filtered[randomIndex];
}
